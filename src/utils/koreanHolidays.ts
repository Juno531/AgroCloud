/**
 * 특정 날짜가 한국 공휴일인지 확인
 * @returns 공휴일 이름 | null
 */
export function getKoreanHolidayName(date: Date): string | null {
    const year = date.getFullYear();
    const mm = String(date.getMonth() + 1).padStart(2, '0');
    const dd = String(date.getDate()).padStart(2, '0');
    const mmdd = `${mm}-${dd}`;
    const yyyymmdd = `${year}-${mmdd}`;

    // 연도별 음력+대체공휴일 우선 조회
    const lunarForYear = LUNAR_HOLIDAYS[year];
    if (lunarForYear) {
        if (lunarForYear[yyyymmdd]) return lunarForYear[yyyymmdd];
        if (lunarForYear[mmdd]) return lunarForYear[mmdd];
    }

    // 고정 공휴일 조회
    return FIXED_HOLIDAYS[mmdd] ?? null;
}

/**
 * 해당 날짜가 빨간날인지 (공휴일 or 일요일)
 */
export function isRedDay(date: Date): boolean {
    return date.getDay() === 0 || getKoreanHolidayName(date) !== null;
}
